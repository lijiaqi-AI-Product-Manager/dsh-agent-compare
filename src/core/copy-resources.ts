import { createHash } from 'node:crypto'
import { lstat, opendir, realpath } from 'node:fs/promises'
import path from 'node:path'
import { git, ownedCopyTree, ownedWorktreeAdmin } from './git.ts'
import { RUN_COORDINATION, type RunRecord } from './types.ts'

export interface CopyResource {
  readonly label: string
  readonly path: string
  readonly bytes: number
  readonly files: number
  readonly links: number
  readonly stopsPreview: boolean
  readonly reason?: string
  /** Dependency and cache directories were sized within a time budget; the totals are a lower bound. */
  readonly estimated?: boolean
}

export interface CopyScanLimits {
  /** Directory entries outside dependency and cache directories. */
  readonly entries?: number
  readonly deadlineMs?: number
  /** Size dependency and cache directories for display. Release skips it. */
  readonly measureDependencies?: boolean
  readonly dependencyEntries?: number
  readonly dependencyDeadlineMs?: number
}

/**
 * Regenerated by the frozen install or by tools inside the copy. Their
 * contents are not candidate source: only their identity is bound to the
 * plan, and their size is measured within a separate budget.
 */
const DEPENDENCY_NAMES = new Set(['node_modules', '.vite'])
const DEPENDENCY_PATHS = new Set([path.join('.yarn', 'cache'), path.join('.yarn', 'unplugged')])
function dependencyDirectory(relative: string): boolean {
  return DEPENDENCY_NAMES.has(path.basename(relative)) || DEPENDENCY_PATHS.has(relative)
}
export interface CopyCleanupPlan {
  readonly version: 1
  readonly runId: string
  readonly rev: number
  readonly state: string
  readonly allowed: boolean
  readonly reasons: string[]
  readonly resources: CopyResource[]
  readonly bytes: number
  readonly token: string
  readonly retained?: { readonly gitRefs?: number; readonly childSessions: number; readonly sealedPatches: number; readonly sourceRepository: string }
}

/** Inspect only. Never follows dependency links or deletes user material. */
export async function planCopyCleanup(record: RunRecord, signal?: AbortSignal, limits: CopyScanLimits = {}): Promise<CopyCleanupPlan> {
  const reasons: string[] = [], resources: CopyResource[] = [], signatures: string[] = []
  const active = new Set(['running', 'adopting', 'recovery'])
  if (record.coordination !== RUN_COORDINATION) reasons.push('旧记录没有当前版本的资源归属凭据，只能查看。')
  if (active.has(record.state) || record.candidates.some(candidate => !['ready', 'failed', 'cancelled', 'interrupted'].includes(candidate.stage))) reasons.push('比较、验收或恢复尚未结束，不能释放副本。')
  if (record.candidates.some(candidate => candidate.stopUnconfirmed) || record.adoption?.rehearsal?.stopUnconfirmed) reasons.push('有任务进程尚未确认退出，请先处理进程状态。')
  if (record.adoption && ['rehearsing', 'writing', 'reverting', 'needs-attention', 'needs-recovery'].includes(record.adoption.state)) reasons.push('采用或恢复仍需要处理，不能释放副本。')
  if (record.revealedAt === undefined && record.state !== 'abandoned') reasons.push('请先完成选择或选择“都不满意”，再查看副本空间；盲选期间不展示两版的规模。')
  if (!reasons.length) {
    const targets = record.candidates.map(candidate => ({ label: candidate.label as string, dir: candidate.dir, token: candidate.ownerToken, tree: candidate.candidateTree, stopsPreview: !!candidate.preview, previewCwd: candidate.preview?.cwd }))
    const rehearsal = record.adoption?.rehearsal
    if (rehearsal?.dir) targets.push({ label: 'R', dir: rehearsal.dir, token: rehearsal.ownerToken, tree: rehearsal.tree, stopsPreview: false, previewCwd: undefined })
    const deadline = Date.now() + (limits.deadlineMs ?? 20_000)
    const dependencyDeadline = Date.now() + (limits.dependencyDeadlineMs ?? 8_000)
    for (const target of targets) {
      signal?.throwIfAborted()
      if (!target.dir) {
        if (target.stopsPreview) reasons.push(`副本 ${target.label}：预览缺少对应副本目录，不能确认本次释放范围。`)
        continue
      }
      const resource = { label: target.label, path: target.dir, bytes: 0, files: 0, links: 0, stopsPreview: target.stopsPreview }
      try {
        const stat = await lstat(target.dir).catch(error => { if (error.code === 'ENOENT') return undefined; throw error })
        if (!stat) {
          if (target.stopsPreview) throw new Error('预览对应的副本目录不存在，请先处理预览状态。')
          continue
        }
        if (target.previewCwd && normalizedPath(target.previewCwd) !== normalizedPath(target.dir)) throw new Error('预览目录与副本不一致，不能确认本次释放范围。')
        if (!target.token || !target.tree) throw new Error('没有完整的归属与封存依据，保留副本。')
        const copy = { repo: record.baseline.repoRoot, owner: { runId: record.runId, label: target.label, token: target.token }, yarnModern: record.acceptance.runtime.yarnModern }
        await ownedWorktreeAdmin(copy.repo, target.dir, copy.owner)
        if (await ownedCopyTree(target.dir, copy, target.tree) !== target.tree) throw new Error('副本有未封存的后续修改，保留文件；请先导出或保存这些改动。')
        const usage = await measureDirectory(target.dir, { deadline, entries: limits.entries ?? 100_000 }, signal)
        const dependencies = limits.measureDependencies === false ? undefined : await measureDependencies(usage.dependencies, { deadline: dependencyDeadline, entries: limits.dependencyEntries ?? 400_000 }, signal)
        const counts = dependencies ? { bytes: usage.counts.bytes + dependencies.bytes, files: usage.counts.files + dependencies.files, links: usage.counts.links + dependencies.links } : usage.counts
        resources.push({ ...resource, ...counts, ...(dependencies?.estimated ? { estimated: true } : {}) })
        signatures.push(usage.fingerprint)
      } catch (error) {
        signal?.throwIfAborted()
        const reason = (error as Error).message
        resources.push({ ...resource, reason })
        reasons.push(`副本 ${target.label}：${reason}`)
      }
    }
    if (!resources.length) reasons.push('没有可释放的工作副本；运行记录与撤销原件继续保留。')
  }
  let retained: CopyCleanupPlan['retained']
  if (record.revealedAt !== undefined || record.state === 'abandoned') {
    const refs = await git(record.baseline.repoRoot, ['for-each-ref', '--format=%(refname)', `refs/agent-compare/${record.runId}/`]).then(text => text.trim() ? text.trim().split('\n').length : 0).catch(() => undefined)
    retained = { ...(refs === undefined ? {} : { gitRefs: refs }), childSessions: record.candidates.filter(candidate => !!candidate.childId).length, sealedPatches: record.candidates.filter(candidate => !!candidate.patchFile).length, sourceRepository: record.baseline.repoRoot }
  }
  const base = { version: 1 as const, runId: record.runId, rev: record.rev, state: record.state, allowed: reasons.length === 0, reasons, resources, bytes: resources.reduce((sum, resource) => sum + resource.bytes, 0), ...(retained ? { retained } : {}) }
  // Sizes are display facts that a release does not recompute; the token
  // binds what will be deleted and the identity of everything inside it.
  const bound = { version: base.version, runId: base.runId, rev: base.rev, state: base.state, allowed: base.allowed, reasons, resources: resources.map(resource => ({ label: resource.label, path: resource.path, stopsPreview: resource.stopsPreview, reason: resource.reason })), signatures }
  return { ...base, token: createHash('sha256').update(JSON.stringify(bound)).digest('hex') }
}

function normalizedPath(value: string): string {
  const resolved = path.resolve(value)
  return process.platform === 'win32' ? resolved.toLowerCase() : resolved
}

const LIMIT_MESSAGE = '空间扫描超过本次上限，尚未确认完整清单；未删除任何副本。'

/**
 * Bind every entry outside dependency and cache directories. Those
 * directories are recorded by identity only and returned for separate sizing,
 * so a large dependency tree cannot keep its copy from ever being released.
 */
async function measureDirectory(root: string, limits: { deadline: number; entries: number }, signal?: AbortSignal): Promise<{ counts: { bytes: number; files: number; links: number }; fingerprint: string; dependencies: string[] }> {
  const canonical = await realpath(root), counts = { bytes: 0, files: 0, links: 0 }, hash = createHash('sha256'), dependencies: string[] = []
  let entries = 0
  const pending = [root]
  while (pending.length) {
    signal?.throwIfAborted()
    if (Date.now() > limits.deadline || entries > limits.entries) throw new Error(LIMIT_MESSAGE)
    const directory = pending.pop()!, before = await lstat(directory)
    if (!before.isDirectory() || before.isSymbolicLink()) throw new Error('扫描期间目录被替换，保留副本。')
    const actual = await realpath(directory), relative = path.relative(canonical, actual)
    if (relative.startsWith('..' + path.sep) || relative === '..' || path.isAbsolute(relative)) throw new Error('资源路径离开了副本，保留目录。')
    // Sort each directory so a repeated inspection produces the same token.
    const names: string[] = []
    const opened = await opendir(directory)
    for await (const entry of opened) {
      signal?.throwIfAborted()
      if (entries + names.length >= limits.entries || Date.now() > limits.deadline) throw new Error(LIMIT_MESSAGE)
      names.push(entry.name)
    }
    names.sort()
    for (const name of names) {
      if (++entries > limits.entries || Date.now() > limits.deadline) throw new Error(LIMIT_MESSAGE)
      const file = path.join(directory, name), stat = await lstat(file), inside = path.relative(root, file)
      if (stat.isDirectory() && !stat.isSymbolicLink() && dependencyDirectory(inside)) {
        // Identity only: installs and dev servers rewrite these freely.
        hash.update(JSON.stringify([inside, stat.dev, stat.ino, 'dependency']))
        dependencies.push(file)
        continue
      }
      hash.update(JSON.stringify([inside, stat.dev, stat.ino, stat.size, stat.mtimeMs, stat.isSymbolicLink()]))
      if (stat.isSymbolicLink()) counts.links++
      else if (stat.isDirectory()) pending.push(file)
      else if (stat.isFile()) { counts.files++; counts.bytes += stat.size }
      else throw new Error('副本中有不支持的特殊文件，保留目录。')
    }
    const after = await lstat(directory)
    if (after.dev !== before.dev || after.ino !== before.ino || after.mtimeMs !== before.mtimeMs || after.isSymbolicLink()) throw new Error('扫描期间副本发生变化，请刷新清单。')
  }
  return { counts, fingerprint: hash.digest('hex'), dependencies }
}

/** Best-effort size of dependency directories. Never follows links and never blocks a release. */
async function measureDependencies(roots: readonly string[], limits: { deadline: number; entries: number }, signal?: AbortSignal): Promise<{ bytes: number; files: number; links: number; estimated: boolean }> {
  const counts = { bytes: 0, files: 0, links: 0, estimated: false }, pending = [...roots]
  let entries = 0
  while (pending.length) {
    signal?.throwIfAborted()
    if (Date.now() > limits.deadline || entries >= limits.entries) { counts.estimated = true; break }
    const directory = pending.pop()!
    try {
      for await (const entry of await opendir(directory)) {
        signal?.throwIfAborted()
        if (++entries >= limits.entries || Date.now() > limits.deadline) { counts.estimated = true; break }
        if (entry.isSymbolicLink()) { counts.links++; continue }
        const file = path.join(directory, entry.name)
        if (entry.isDirectory()) { pending.push(file); continue }
        if (entry.isFile()) { counts.files++; counts.bytes += (await lstat(file)).size }
      }
    } catch (error) {
      signal?.throwIfAborted()
      // Sizing is display-only: an unreadable cache entry makes the total a lower bound.
      if ((error as NodeJS.ErrnoException).code !== 'ENOENT') counts.estimated = true
    }
    if (counts.estimated) break
  }
  return counts
}
